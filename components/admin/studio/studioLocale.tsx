export function StudioLocaleProvider({locale, children}: {locale: "fr" | "en"; children: ReactNode}) {
 return <StudioLocale.Provider value={locale}>{children}</StudioLocale.Provider>;
}
export function useStudioLocale() {
 const locale = useContext(StudioLocale);
 return {locale, t: (text: string) => locale === "en" ? (english[text] ?? text) : text, number: (value: number | undefined) => value === undefined ? "N/A" : new Intl.NumberFormat(locale === "en" ? "en-CA" : "fr-CA").format(value), date: (value: string) => new Intl.DateTimeFormat(locale === "en" ? "en-CA" : "fr-CA", {day: "numeric", month:"short", year:"numeric",timeZone:"UTC"}).format(new Date(value))};
}
